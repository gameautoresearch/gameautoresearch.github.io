"""Stage the exact earliest retained integration learner in a private overlay.

This is an integration-authored PPO learner using pinned upstream crforge, not an
upstream learner. Its original model already supports trimming. No archived file
is edited and no experiment is launched by this helper.
"""
from pathlib import Path
import hashlib,io,json,tarfile
HERE=Path(__file__).resolve().parent;ROOT=HERE.parents[2]
ORIGIN=Path('evidence/clash-implementation/first-smoke')
OVERLAY=Path('evidence/clash-implementation/native-performance-20261108/original-integration')
SNAPSHOT=OVERLAY/'snapshots/first-smoke'
ARCHIVE_SHA256='5ef7b21ffbb27b5a4b8d7dfc890580b43bd21153ccc086e527d0e36e4aaca051'
MODEL_SHA256='2302de2b57319d58dc3ab3526c2c6d3b5590de97a443ea329f3dda0a6c3bf660'
RUNNER_SHA256='c5dc2e18912c60df9376fc3eb0e02712c793dfed08fad689f259b355f9213d93'
MANIFEST_DIGEST='6a69fe502987d66cd70e65bf20e7cf17fe236694f5cd1908046095e775e0be89'
PIN='f0659dafabfb9d2a4a8d3b22a9d14de306f5e4de'

def sha(data):return hashlib.sha256(data).hexdigest()

def _source(root):
    folder=Path(root)/ORIGIN;archive=folder/'source.tar.gz';manifest=json.loads((folder/'manifest.json').read_text());payload=archive.read_bytes()
    if sha(payload)!=ARCHIVE_SHA256 or manifest['source_archive_sha256']!=ARCHIVE_SHA256:raise ValueError('original integration archive differs')
    unsigned=dict(manifest);embedded=unsigned.pop('manifest_sha256')
    if embedded!=MANIFEST_DIGEST or sha(json.dumps(unsigned,sort_keys=True,separators=(',',':')).encode())!=embedded:raise ValueError('original manifest digest differs')
    result={}
    with tarfile.open(fileobj=io.BytesIO(payload),mode='r:gz') as source:
        for entry in source.getmembers():
            if not entry.isfile() or not entry.name.startswith('integration/'):continue
            relative=Path(entry.name).relative_to('integration')
            if relative.is_absolute() or '..' in relative.parts:raise ValueError('unsafe original source path')
            data=source.extractfile(entry).read()
            if sha(data)!=manifest['integration_source_sha256'].get(str(relative)):raise ValueError('original source digest differs: '+str(relative))
            result[relative]=data
    if set(map(str,result))!=set(manifest['integration_source_sha256']):raise ValueError('original integration source map incomplete')
    return manifest,result

def add_original_to_tar(target,root=ROOT):
    """Append exact source and provenance to an already-open private overlay TarFile."""
    manifest,files=_source(root);members=[]
    for relative,payload in sorted(files.items()):
        name=str(SNAPSHOT/'integrations/clash'/relative);entry=tarfile.TarInfo(name);entry.size=len(payload);entry.mode=0o444;entry.mtime=0;target.addfile(entry,io.BytesIO(payload));members.append(name)
    provenance=dict(format=1,archive=str(ORIGIN/'source.tar.gz'),archive_sha256=ARCHIVE_SHA256,manifest=manifest,upstream_learner=False,earliest_model_already_has_optional_trimming=True)
    payload=(json.dumps(provenance,indent=2)+'\n').encode();name=str(OVERLAY/'overlay-provenance.json');entry=tarfile.TarInfo(name);entry.size=len(payload);entry.mode=0o444;target.addfile(entry,io.BytesIO(payload));members.append(name)
    return dict(status='prepared',members=members,source_archive_sha256=ARCHIVE_SHA256,runner_sha256=RUNNER_SHA256,model_sha256=MODEL_SHA256)

def prepare_original(root=ROOT):
    """Validate staged source and create runtime references to owning pinned assets."""
    root=Path(root).resolve();snapshot=root/SNAPSHOT;receipt=root/OVERLAY/'overlay-provenance.json'
    if receipt.exists():manifest=json.loads(receipt.read_text())['manifest']
    else:
        # Local analysis layout generated by the read-only archival inventory.
        historical=root/OVERLAY/'records/first-smoke/manifest.json'
        if not historical.exists():raise FileNotFoundError('stage original integration with add_original_to_tar first')
        manifest=json.loads(historical.read_text())
    if manifest['source_archive_sha256']!=ARCHIVE_SHA256 or manifest['engine_commit']!=PIN:raise ValueError('original staged provenance differs')
    unsigned=dict(manifest);embedded=unsigned.pop('manifest_sha256')
    if embedded!=MANIFEST_DIGEST or sha(json.dumps(unsigned,sort_keys=True,separators=(',',':')).encode())!=MANIFEST_DIGEST:raise ValueError('original staged manifest digest differs')
    integration=snapshot/'integrations/clash'
    for relative,want in manifest['integration_source_sha256'].items():
        if sha((integration/relative).read_bytes())!=want:raise ValueError('original staged source differs: '+relative)
    for relative in ('candidates','.cache-crforge','evidence'):
        link=snapshot/relative;wanted=root/relative
        if link.exists() or link.is_symlink():
            if link.resolve()!=wanted.resolve():
                if relative=='candidates' and (link/'crforge').resolve()==(wanted/'crforge').resolve():continue
                raise ValueError('original runtime reference differs: '+relative)
        else:link.symlink_to(wanted,target_is_directory=True)
    return dict(snapshot=snapshot,runner=integration/'runner.py',model=integration/'model.py',manifest=manifest)
