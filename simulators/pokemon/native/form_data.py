def enrich_fixture(data):
    """Add public form identities to old fixture metadata without editing receipts."""
    if 'metadata' not in data:
        return
    from .reset import visible_token
    from .rules import TYPES
    known = {row['id'] for row in data['metadata']['species']}
    rows = list(data['metadata']['species'])
    for row in FORM_RECORDS:
        if row['id'] in known:
            continue
        types = [TYPES.index(t) for t in row['types']]
        rows.append(dict(id=row['id'], token=visible_token('species', row['name']),
                         types=types+[-1]*(2-len(types)),
                         type_tokens=[visible_token('type', t) for t in row['types']]+[0]*(2-len(types)),
                         stats=[row['stats'][k] for k in ('atk','def','spa','spd','spe')]))
    data['metadata'] = {**data['metadata'], 'species': rows}


def install_fixture_forms(mon, reference, species_ids):
    """Materialize the same public forms from a constructed oracle's set EV/IVs."""
    from .rules import TYPES
    original = reference.get('set_species', reference['species'])
    group = None
    for family, (name, names) in enumerate(FORM_GROUPS.items(), 1):
        ident = ''.join(c for c in name.lower() if c.isalnum())
        if original == ident or (name == 'Minior' and original.startswith('minior') and original != 'miniormeteor'):
            group = names
            break
    if group is None:
        return
    records = {row['name']: row for row in FORM_RECORDS}
    names = list(group)
    if names[0] == 'Minior' and original != 'minior':
        # Cosmetic cores share stats, but retain their own public identity.
        base = dict(records['Minior'], id=original)
    else:
        base = records[names[0]]
    selected = [base, *[records[n] for n in names[1:]]]
    mon.form_family, mon.form_count = family, len(selected)
    mon.form_current = next(i for i, row in enumerate(selected) if row['id'] == reference['species'])
    mon.form_permanent = mon.form_current if family in (3, 4, 5, 8, 9, 10, 11, 12) else 0
    for form, row in zip(mon.forms, selected):
        form.species = species_ids[row['id']]
        form.type[:] = [TYPES.index(t) for t in row['types']]+[-1]*(2-len(row['types']))
        form.base_speed = row['stats']['spe']
        form.base_attack, form.weight_hg = row['stats']['atk'], row['weight_hg']
        for i, key in enumerate(('hp','atk','def','spa','spd','spe')):
            iv = reference.get('ivs', {}).get(key, 31)
            ev = reference.get('evs', {}).get(key, 0)
            value = (2*row['stats'][key]+iv+ev//4+(0 if i else 100))*mon.level//100+(5 if i else 10)
            if i:
                form.stats[i-1] = value
            else:
                form.maxhp = row['fixed_hp'] or value


